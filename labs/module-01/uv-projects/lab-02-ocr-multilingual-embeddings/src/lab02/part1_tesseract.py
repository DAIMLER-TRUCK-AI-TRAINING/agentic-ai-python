"""Part 1 — generate the four sample documents and run Tesseract on them."""

from __future__ import annotations

import functools
import json
import shutil
import subprocess
import sys
import time

import pandas as pd
import pytesseract
from PIL import Image

from .common import DATA_DIR, show, step

SAMPLES_DIR = DATA_DIR / "samples"
CLEAN_INVOICE, SCANNED_INVOICE = "INV-88341_clean.png", "INV-88342_scan.png"
TICKET_IMAGES = ("INC-104233_ticket.png", "INC-104251_photo.png")


@functools.cache
def ground_truth() -> dict[str, dict]:
    """The known text and fields of every sample; generates the images first if they are missing."""
    if not (SAMPLES_DIR / "ground_truth.json").exists():  # the images are generated, not committed
        subprocess.run([sys.executable, str(DATA_DIR / "make_samples.py")], check=True)
    return json.loads((SAMPLES_DIR / "ground_truth.json").read_text(encoding="utf-8"))


def tesseract_ok() -> bool:
    return shutil.which("tesseract") is not None


def open_sample(name: str) -> Image.Image:
    return Image.open(SAMPLES_DIR / name)


def word_table(name: str) -> pd.DataFrame:
    """Every recognised word with its position and a confidence from 0 to 100."""
    words = pytesseract.image_to_data(open_sample(name), output_type=pytesseract.Output.DATAFRAME)
    return words[(words.conf >= 0) & words.text.notna() & (words.text.astype(str).str.strip() != "")]


def run() -> None:
    truth = ground_truth()
    step("The four documents (data/samples/, generated by data/make_samples.py)")
    show(
        pd.DataFrame([{"file": n, "type": i["doc_type"], "condition": i["condition"]} for n, i in truth.items()]),
        index=False,
    )
    print(f"Open them to look: {SAMPLES_DIR}")
    if not tesseract_ok():
        print("❌ Tesseract is not installed: the Tesseract steps skip (see labs/setup/README.md).")
        return
    print(f"Tesseract {pytesseract.get_tesseract_version()}")

    step(f"Plain Tesseract on {CLEAN_INVOICE}, default settings")
    started = time.perf_counter()
    text = pytesseract.image_to_string(open_sample(CLEAN_INVOICE))
    print(f"({time.perf_counter() - started:.2f}s, local, no network)\n")
    print(text)

    step(f"Word-level output for {SCANNED_INVOICE}: the ten least confident words")
    words = word_table(SCANNED_INVOICE)
    print(f"{len(words)} words on the scan · median confidence {words.conf.median():.0f}")
    show(words.sort_values("conf")[["text", "conf", "left", "top", "block_num", "line_num"]].head(10), index=False)
